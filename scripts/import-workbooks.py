"""Import both supplied workbooks without modifying them. Requires openpyxl.

python scripts/import-workbooks.py --power <power.xlsx> --strips <strips.xlsx>
Zero is valid. Missing cells, reordered headers, or inconsistent totals fail.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import openpyxl

GROUPS = [
    ('iphone', 'iPhone*2', 2), ('android', '安卓手机*2', 2),
    ('macbook', 'MacBook*2', 2), ('gaming', '游戏笔记本*2', 2),
    ('tablet', '平板电脑*2', 2), ('led', '宿舍LED照明', 1),
    ('lamp', '台灯*4', 4), ('ac', '空调', 1), ('kettle', '电热水壶', 1),
    ('dryer', '电吹风', 1), ('washer', '洗烘一体洗衣机', 1), ('cooker', '电煮锅', 1),
]

def number(v):
    if not isinstance(v, (float, int)) or isinstance(v, bool) or not math.isfinite(v) or v < 0:
        raise ValueError(f'Expected a nonnegative number, got {v!r}')
    return v

def read_power(path):
    book = openpyxl.load_workbook(path, data_only=True)
    summary, matrix = book['设备功率与耗电量汇总'], book['24小时设备功率矩阵']
    names = [name for _, name, _ in GROUPS]
    assert [summary.cell(4, c).value for c in range(2, 14)] == names
    assert [matrix.cell(2, c).value for c in range(2, 14)] == names
    times = [f'{i//6:02d}:{i%6*10:02d}' for i in range(144)]
    assert [matrix.cell(i+3, 1).value for i in range(144)] == times
    assert matrix.cell(147, 1).value == '24:00'
    rows = [[number(matrix.cell(r, c).value) for c in range(2, 15)] for r in range(3, 147)]
    for row in rows:
        assert abs(sum(row[:12])-row[12]) < 1e-8
    groups = []
    for col, (gid, name, units) in enumerate(GROUPS):
        values = [row[col] for row in rows]
        avg, peak, energy, hours = sum(values)/144, max(values), sum(values)/6, sum(v>0 for v in values)/6
        for r, val in [(5, avg), (6, peak), (7, energy/1000), (8, hours)]:
            assert abs(number(summary.cell(r, col+2).value)-val) < 1e-8, (name, r)
        groups.append(dict(id=gid, name=name, units=units, avgW=avg, peakW=peak,
                           energyWh=energy, hours=hours, series=values))
    total_series = [row[12] for row in rows]
    total = dict(id='all', name='全部设备', units=1, avgW=sum(total_series)/144,
                 peakW=max(total_series), energyWh=sum(total_series)/6,
                 hours=sum(g['hours'] for g in groups), series=total_series)
    assert abs(summary.cell(5,14).value-total['avgW']) < 1e-8
    assert summary.cell(6,14).value == total['peakW']
    assert abs(summary.cell(7,14).value*1000-total['energyWh']) < 1e-8
    return groups, total, times

def read_strips(path):
    sheet = openpyxl.load_workbook(path, data_only=True).worksheets[0]
    assert list(next(sheet.values)) == ['名称', '插孔数目', '最大功率', '体积', '价格']
    result = []
    for row, (name, ports, power, size, price) in enumerate(list(sheet.values)[1:], 2):
        if not name:
            continue
        result.append(dict(id=f'strip-{row}', name=name,
                           ports=str(int(ports))+' 孔' if isinstance(ports, (int,float)) else ports,
                           maxW=float(power.lower().replace('w','').strip()),
                           size=size.replace('*','×').replace('x','×'),
                           price=float(price.lower().replace('rmb','').replace('rm','').strip())))
    assert len(result) == 12
    return result

def emit(power, strips, out):
    groups, total, times = read_power(power)
    specs = read_strips(strips)
    def dump(value): return json.dumps(value, ensure_ascii=False, separators=(',', ':'))
    def source(path): return f'// Source: {path.name}\n// SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}\n'
    out.mkdir(parents=True, exist_ok=True)
    (out/'measured.ts').write_text(source(power)+'''// Generated by scripts/import-workbooks.py. Do not edit numeric data manually.
export type MeasuredGroup = {
  id: string
  name: string
  units: number
  avgW: number
  peakW: number
  energyWh: number
  hours: number
  series: number[]
}
export const MEASURED_INTERVAL_MINUTES = 10
export const MEASURED_INTERVALS = 144
'''+f'export const MEASURED_TIMES: string[] = {dump(times)}\n'
        +'export const MEASURED_GROUPS: MeasuredGroup[] = [\n'+',\n'.join(dump(g) for g in groups)+'\n]\n'
        +f'export const MEASURED_TOTAL: MeasuredGroup = {dump(total)}\n'
        +'''export const MEASURED_MAP = Object.fromEntries(
  MEASURED_GROUPS.map(group => [group.id, group]),
) as Record<string, MeasuredGroup>
''', encoding='utf-8')
    (out/'strips.ts').write_text(source(strips)+'''// Generated by scripts/import-workbooks.py. E2 "28.9rm" is normalized to CNY 28.9.
// "孔" counts openings, not the number of appliances that can be connected.
export type StripSpec = { id: string; name: string; ports: string; maxW: number; size: string; price: number }
export const STRIP_SPECS: StripSpec[] = [
'''+',\n'.join(dump(s) for s in specs)+'\n]\n'
        +'''// Four-outlet reference specification for the desks; geometry is schematic.
export const DESK_STRIP = STRIP_SPECS.find(s => s.name === '公牛407四插位')!
''', encoding='utf-8')
    print(f'Validated {len(groups)*144} readings, 12 strip specifications; total {total["energyWh"]/1000:.6f} kWh')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--power', type=Path, required=True)
    parser.add_argument('--strips', type=Path, required=True)
    parser.add_argument('--out', type=Path, default=Path(__file__).resolve().parent.parent/'src/data')
    args = parser.parse_args()
    emit(args.power, args.strips, args.out)
